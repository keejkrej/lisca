from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
import typer


app = typer.Typer(
    add_completion=False,
    no_args_is_help=True,
    help=(
        "Plot all ROI traces from a long-form stain timeseries CSV using low-opacity "
        "lines and no legend."
    ),
)


def load_timeseries(csv_path: Path) -> pd.DataFrame:
    df = pd.read_csv(csv_path)
    required = {"roi", "t", "corrected"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            f"{csv_path} is missing required columns for plotting: {sorted(missing)}"
    )
    return df.sort_values(["roi", "t"]).reset_index(drop=True)


def load_events(event_csv: Path) -> pd.DataFrame:
    df = pd.read_csv(event_csv)
    required = {"roi", "detected", "event_t", "event_value"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            f"{event_csv} is missing required columns for event overlay: {sorted(missing)}"
        )
    return df.loc[df["detected"].astype(bool)].sort_values("roi").reset_index(drop=True)


def default_output_plot_path(csv_path: Path, output_plot: Path | None) -> Path:
    plot_path = output_plot or csv_path.with_suffix(".png")
    return plot_path.resolve()


def write_trace_plot(
    df: pd.DataFrame,
    output_plot: Path,
    *,
    color: str,
    alpha: float,
    linewidth: float,
    events_df: pd.DataFrame | None,
    event_color: str,
    event_alpha: float,
    event_marker_size: float,
    event_marker_linewidth: float,
    title: str | None,
) -> None:
    fig, ax = plt.subplots(figsize=(12, 7))
    for _, roi_df in df.groupby("roi", sort=True):
        ax.plot(
            roi_df["t"],
            roi_df["corrected"],
            color=color,
            alpha=alpha,
            linewidth=linewidth,
        )

    if events_df is not None and not events_df.empty:
        ax.scatter(
            events_df["event_t"],
            events_df["event_value"],
            color=event_color,
            alpha=event_alpha,
            marker="x",
            s=event_marker_size,
            linewidths=event_marker_linewidth,
        )

    ax.set_xlabel("frame")
    ax.set_ylabel("sum - area*q25")
    ax.grid(alpha=0.2, linewidth=0.5)
    if title is not None:
        ax.set_title(title)

    output_plot.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_plot, dpi=150, bbox_inches="tight")
    plt.close(fig)


@app.command()
def cli(
    timeseries_csv: Path = typer.Argument(
        ...,
        exists=True,
        dir_okay=False,
        help="Long-form ROI timeseries CSV generated by apoptosis stain extract-timeseries.",
    ),
    output_plot: Path | None = typer.Option(
        None,
        "--output-plot",
        help="Output PNG path. Default: same path as the CSV with .png extension.",
    ),
    event_csv: Path | None = typer.Option(
        None,
        "--event-csv",
        exists=True,
        dir_okay=False,
        help="Optional event CSV generated by apoptosis stain detect-events to overlay event markers.",
    ),
    alpha: float = typer.Option(
        0.12,
        "--alpha",
        min=0.0,
        max=1.0,
        help="Per-trace opacity.",
    ),
    linewidth: float = typer.Option(
        1.0,
        "--linewidth",
        min=0.1,
        help="Per-trace line width.",
    ),
    color: str = typer.Option(
        "#c03a2b",
        "--color",
        help="Matplotlib color for all traces.",
    ),
    event_color: str = typer.Option(
        "#0b5fff",
        "--event-color",
        help="Matplotlib color for event markers.",
    ),
    event_alpha: float = typer.Option(
        0.95,
        "--event-alpha",
        min=0.0,
        max=1.0,
        help="Opacity for event markers.",
    ),
    event_marker_size: float = typer.Option(
        110.0,
        "--event-marker-size",
        min=1.0,
        help="Marker area for event crosses.",
    ),
    event_marker_linewidth: float = typer.Option(
        2.2,
        "--event-marker-linewidth",
        min=0.1,
        help="Line width for event crosses.",
    ),
    title: str | None = typer.Option(
        None,
        "--title",
        help="Optional plot title. Default: no title.",
    ),
) -> None:
    timeseries_csv = timeseries_csv.resolve()
    df = load_timeseries(timeseries_csv)
    events_df = load_events(event_csv.resolve()) if event_csv is not None else None
    resolved_output_plot = default_output_plot_path(timeseries_csv, output_plot)
    write_trace_plot(
        df,
        resolved_output_plot,
        color=color,
        alpha=alpha,
        linewidth=linewidth,
        events_df=events_df,
        event_color=event_color,
        event_alpha=event_alpha,
        event_marker_size=event_marker_size,
        event_marker_linewidth=event_marker_linewidth,
        title=title,
    )
    print(f"Wrote plot: {resolved_output_plot}")


def main(argv: list[str] | None = None, *, prog_name: str = "apoptosis stain plot-timeseries") -> None:
    app(args=argv, prog_name=prog_name)
