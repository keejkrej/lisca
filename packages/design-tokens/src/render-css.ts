function block(selector: string, entries: { readonly [key: string]: string }): string {
  const body = Object.entries(entries)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `${selector} {\n${body}\n}`;
}

export function renderVariablesCss(): string {
  const radius = Object.entries(tokens.radius)
    .filter(([name]) => name !== "base")
    .map(([name, value]) => `  --radius-${name}: ${value};`)
    .join("\n");
  const colors = themeColorNames.map((name) => `  --color-${name}: var(--${name});`).join("\n");
  const theme = `@theme inline {
  /* Lyra is square. Every radius token is 0 so rounded-* utilities stay boxy. */
${radius}

  --font-sans: ${tokens.fontSans};
  --font-heading: var(--font-sans);

${colors}
  --color-gfp: var(--instrument-gfp);
  --color-lisca-brand: var(--lisca-brand);
  --color-lisca-brand-foreground: var(--lisca-brand-foreground);
  --color-lisca-brand-muted: var(--lisca-brand-muted);
  --color-ink: var(--instrument-ink);
  --color-mute: var(--instrument-mute);
  --color-paper: var(--instrument-paper);
  --color-rule: var(--instrument-rule);
  --color-stage: var(--instrument-stage);

  --spacing-rail: ${tokens.geometry.rail};
  --spacing-rail-content: ${tokens.geometry.railContent};
  --spacing-topbar: ${tokens.geometry.topbar};
  --spacing-rail-inset: ${tokens.geometry.railInset};
}`;

  const apps = (Object.keys(tokens.brand) as Array<keyof typeof tokens.brand>)
    .filter((app) => app !== "foreground")
    .map(
      (app) => `[data-lisca-app="${app}"] {
  --lisca-brand: ${tokens.brand[app]};
  --lisca-brand-foreground: ${tokens.brand.foreground};
}`,
    )
    .join("\n\n");

  return `/* Generated by packages/design-tokens/scripts/generate.ts. Do not edit. */

@custom-variant dark (&:where(.dark, .dark *));

${theme}

${block(":root", tokens.light)}

${block(".dark", tokens.dark)}

/*
 * Per-app accents. The same fill in light and dark: primary actions, focus
 * rings, selected nav, and pressed Show/Edit/Expert toggles. The label stays
 * ink. GFP and destructive stay separate.
 */
${apps}

.lisca-instrument-shell {
  --instrument-gfp: ${tokens.instrument.gfp};
  --instrument-ink: var(--foreground);
  --instrument-mute: var(--muted-foreground);
  --instrument-rule: color-mix(in oklab, var(--foreground) 12%, transparent);
  --instrument-paper: ${tokens.instrument.paper};
  --instrument-stage: ${tokens.instrument.stage};
}

.dark .lisca-instrument-shell {
  --instrument-paper: ${tokens.instrument.paperDark};
  --instrument-stage: ${tokens.instrument.stageDark};
}
`;
}
